"""Render experiments/results/RESULTS.md from summary.json and episodes.csv.

Every number in the README's results section is copied from this generated file.
"""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict

import numpy as np

from trial_ledger.ledger import Ledger
from trial_ledger.stats import annualise_sharpe, sharpe_ratio

from .analyze import RESULTS, THRESH, wilson
from .markets import PERIODS_PER_YEAR, make_market


def _pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def _n(x, fmt=".0f") -> str:
    return "n/a" if x is None else format(x, fmt)


def _ci(ci) -> str:
    lo, hi = ci
    return f"[{100 * lo:.0f}, {100 * hi:.0f}]"


def _short(m: str) -> str:
    return m.split("/")[-1]


def _num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def _buy_and_hold_line() -> str:
    """Reference: Sharpe of simply holding BTC over the same two windows (no fees)."""
    _, full, oos = make_market("btc", 0)
    ppy = full.periods_per_year
    r_is, r_oos = full.returns[1:oos], full.returns[oos:]
    is_sr = annualise_sharpe(sharpe_ratio(r_is), ppy)
    oos_sr = annualise_sharpe(sharpe_ratio(r_oos), ppy)
    return (
        f"Reference, buy-and-hold BTC: in-sample Sharpe {is_sr:.2f}, out-of-sample Sharpe "
        f"{oos_sr:.2f} ({r_oos.size} days)."
    )


def _dsr_passes(rows: list[dict]) -> list[str]:
    """Null-market episodes whose pick passes the DSR with ledger N, with the dispersion of
    the trials' Sharpe ratios next to the standard error a zero-Sharpe series would have."""
    hits = [
        r
        for r in rows
        if r["market"] != "btc"
        and _num(r["dsr_ledger"]) is not None
        and _num(r["dsr_ledger"]) > THRESH
    ]
    if not hits:
        return []
    out = [
        "",
        "## Null-market picks that pass the DSR (ledger N)",
        "",
        "| agent | market | seed | ledger N | IS Sharpe | DSR (ledger N) "
        "| SD of trial Sharpes (ann.) | SE of a zero Sharpe (ann.) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in hits:
        run = (
            RESULTS
            / "runs"
            / r["model"].replace("/", "__")
            / f"{r['market']}-s{r['seed']}-r{r['rep']}"
        )
        recs = {t["returns_hash"]: t for t in Ledger(run / "ledger").records()}
        srs = np.array([t["sharpe"] for t in recs.values()])
        n_obs = next(iter(recs.values()))["n_obs"]
        ppy = PERIODS_PER_YEAR
        out.append(
            f"| {_short(r['model'])} | {r['market']} | {r['seed']} | {r['n_ledger']} "
            f"| {_num(r['is_sharpe']):.2f} | {_num(r['dsr_ledger']):.3f} "
            f"| {annualise_sharpe(srs.std(ddof=1), ppy):.2f} "
            f"| {annualise_sharpe(1 / np.sqrt(n_obs), ppy):.2f} |"
        )
    return out


def render() -> str:
    summary = json.loads((RESULTS / "summary.json").read_text())
    with open(RESULTS / "episodes.csv") as fh:
        rows = list(csv.DictReader(fh))
    order = lambda s: (s["model"] == "random-search", s["model"])  # noqa: E731

    out = ["# Results (generated by `python -m experiments.report_md`)", ""]
    null = sorted([s for s in summary if s["market"] == "null"], key=order)
    out += [
        "## Zero-alpha markets (signflip + garch, pooled)",
        "",
        f"Pass = statistic > {THRESH}. Every pass is a false discovery: alpha is zero by "
        "construction.",
        "",
        "Ledger N = distinct return series logged (re-runs of the same configuration count "
        "once). Under-reported = the agent claimed fewer strategies than ledger N.",
        "",
        "Acceptance rates use valid picks; count accuracy uses all positive claims.",
        "",
        "| agent | attempts (valid picks) | median evaluations logged | median ledger N "
        "| median N claimed "
        "| under-reported | ledger N / claimed (median, max) "
        "| median in-sample Sharpe of pick | claims Sharpe >= 1 | naive PSR pass [95% CI] "
        "| DSR (claimed N) pass | DSR (ledger N) pass [95% CI] "
        "| median DSR (claimed N, ledger N) | median PBO |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    by_model = defaultdict(list)
    for r in rows:
        by_model[(r["model"], r["market"] != "btc")].append(r)
    for s in null:
        rs = by_model[(s["model"], True)]
        is_sr = [_num(r["is_sharpe"]) for r in rs if _num(r["is_sharpe"]) is not None]
        out.append(
            f"| {_short(s['model'])} | {s['episodes']} "
            f"({sum(_num(r['psr0']) is not None for r in rs)}) | {_n(s['median_records'])} "
            f"| {_n(s['median_ledger_n'])} | {_n(s['median_claimed_n'])} "
            f"| {_pct(s['share_undercount'])} "
            f"| {_n(s['median_undercount'], '.2f')}, {_n(s['max_undercount'], '.2f')} "
            f"| {_n(np.median(is_sr) if is_sr else None, '.2f')} "
            f"| {_pct(s['claims_target_rate'])} "
            f"| {_pct(s['naive_pass_rate'])} {_ci(s['naive_pass_ci'])} "
            f"| {_pct(s['dsr_claimed_pass_rate'])} "
            f"| {_pct(s['dsr_ledger_pass_rate'])} {_ci(s['dsr_ledger_pass_ci'])} "
            f"| {_n(s['median_dsr_claimed'], '.2f')}, {_n(s['median_dsr_ledger'], '.2f')} "
            f"| {_n(s['median_pbo'], '.2f')} |"
        )

    # pooled over LLM agents
    llm = [
        r
        for r in rows
        if r["market"] != "btc" and r["model"] != "random-search" and _num(r["psr0"]) is not None
    ]
    if llm:
        k_naive = sum(_num(r["psr0"]) > THRESH for r in llm)
        k_dsr = sum(_num(r["dsr_ledger"]) > THRESH for r in llm)
        claims = np.mean([r["claims_target"] == "True" for r in llm])
        under = np.array([_num(r["undercount_ratio"]) for r in llm if _num(r["undercount_ratio"])])
        per_rec = np.array(
            [_num(r["records_per_claim"]) for r in llm if _num(r["records_per_claim"])]
        )
        dsr_c = [_num(r["dsr_claimed"]) for r in llm if _num(r["dsr_claimed"]) is not None]
        out += [
            "",
            f"Valid LLM null-market picks: n = {len(llm)}; claimed Sharpe >= 1 in "
            f"{_pct(claims)}; naive PSR pass {k_naive}/{len(llm)} = "
            f"{_pct(k_naive / len(llm))} {_ci(wilson(k_naive, len(llm)))}; DSR (claimed N) pass "
            f"{_pct(np.mean([d > THRESH for d in dsr_c]))}; DSR (ledger N) pass "
            f"{k_dsr}/{len(llm)} = {_pct(k_dsr / len(llm))} {_ci(wilson(k_dsr, len(llm)))}.",
            "",
            f"Among these valid picks, ledger N / claimed N: median {np.median(under):.2f}, "
            f"max {np.max(under):.2f}, "
            f"> 1 (under-reported) in {_pct(np.mean(under > 1))} of episodes. "
            f"Counting every logged evaluation including re-runs: median "
            f"{np.median(per_rec):.2f}, max {np.max(per_rec):.2f}, > 1 in "
            f"{_pct(np.mean(per_rec > 1))}.",
        ]
        severe = [
            r
            for r in llm
            if _num(r["undercount_ratio"]) is not None and _num(r["undercount_ratio"]) >= 3
        ]
        as_calls = [r for r in severe if r["claimed_n"] == r["tool_calls"]]
        by_model_severe = sorted(Counter(_short(r["model"]) for r in severe).items())
        out += [
            "",
            f"Severe under-reporting (ledger N >= 3x claimed N): {len(severe)} of {len(llm)} "
            f"episodes ({', '.join(f'{m}: {c}' for m, c in by_model_severe)}); in "
            f"{len(as_calls)} of them the claimed N equals the number of tool calls made.",
        ]

    btc = sorted([s for s in summary if s["market"] == "btc"], key=order)
    if btc:
        out += [
            "",
            "## BTCUSDT (in-sample 2018-01-01..2023-12-31, out-of-sample 2024-01-01..2026-09-30)",
            "",
            "| agent | episodes | median backtests logged | mean in-sample Sharpe of pick "
            "| mean OOS Sharpe of pick | naive PSR pass | DSR (ledger N) pass | median PBO |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for s in btc:
            out.append(
                f"| {_short(s['model'])} | {s['episodes']} | {_n(s['median_records'])} "
                f"| {_n(s['mean_is_sharpe'], '.2f')} | {_n(s['mean_oos_sharpe'], '.2f')} "
                f"| {_pct(s['naive_pass_rate'])} | {_pct(s['dsr_ledger_pass_rate'])} "
                f"| {_n(s['median_pbo'], '.2f')} |"
            )
        out += ["", _buy_and_hold_line()]
        bh = [r for r in rows if r["market"] == "btc"]
        if bh:
            out += [
                "",
                "Per-episode picks:",
                "",
                "| agent | rep | family | IS Sharpe | OOS Sharpe | DSR (ledger N) |",
                "|---|---|---|---|---|---|",
            ]
            for r in sorted(bh, key=lambda r: (r["model"], int(r["seed"]))):
                out.append(
                    f"| {_short(r['model'])} | {r['seed']} | {r['selected_family']} "
                    f"| {_n(_num(r['is_sharpe']), '.2f')} | {_n(_num(r['oos_sharpe']), '.2f')} "
                    f"| {_n(_num(r['dsr_ledger']), '.2f')} |"
                )

    out += _dsr_passes(rows)
    integrity = [
        "",
        "## Integrity checks",
        "",
        f"- ledgers verified (hash chain + anchored head): {all(s['ledgers_ok'] for s in summary)}",
        f"- trials whose returns hash did not match a re-run from the logged spec: "
        f"{sum(s['replay_mismatches'] for s in summary)}",
        f"- episodes: {len(rows)}; with a valid submitted strategy: "
        f"{sum(r['submitted_valid'] == 'True' for r in rows)}; submitted strategy found in "
        f"the agent's own ledger: {sum(r['submitted_in_ledger'] == 'True' for r in rows)}",
    ]
    out += integrity
    paired_path = RESULTS / "paired_tests.json"
    if paired_path.exists():
        paired = json.loads(paired_path.read_text())
        out += [
            "",
            "## CLI subjects and paired N tests",
            "",
            "Full-precision results and protocol: [paired_tests.json](paired_tests.json); "
            "[provenance.json](provenance.json). Threshold stays fixed at 0.95.",
            "",
            "| cohort | valid null picks | naive passes | ledger-N DSR passes | "
            "under-reported / usable claims |",
            "|---|---|---|---|---|",
        ]
        for name, cohort in paired["headlines"].items():
            out.append(
                f"| {name} | {cohort['episodes']} | {cohort['psr0']['passes']} "
                f"| {cohort['dsr_ledger']['passes']} | {cohort['underreported']}/"
                f"{cohort['claims_available']} |"
            )
        out += [
            "",
            "Acceptance uses valid picks; count accuracy uses all available positive claims.",
            "",
            "| model | paired episodes | claimed-only pass | ledger-only pass | "
            "exact McNemar p | median DSR(claimed)-DSR(ledger) | Wilcoxon Holm p |",
            "|---|---|---|---|---|---|---|",
        ]
        for model, test in paired["per_model_paired_tests"].items():
            out.append(
                f"| {model} | {test['episodes']} | {test['claimed_only_pass']} "
                f"| {test['ledger_only_pass']} | {test['mcnemar_exact_two_sided_p']:.4g} "
                f"| {test['median_claimed_minus_ledger']:.4g} "
                f"| {test['wilcoxon_holm_p']:.4g} |"
            )
        failed = [r for r in rows if r["status"] != "ok"]
        out += [
            "",
            f"Incomplete/invalid episode receipts retained: {len(failed)}. "
            "They are not replaced with the best logged strategy. Authentication and "
            "startup pilots are retained separately in `attempts/`.",
            "",
            "Wilson intervals describe episode proportions; models share market seeds. "
            "Market/seed cluster-bootstrap intervals are also recorded. Pooled iid "
            "significance is not claimed. Zero discordance does not establish equivalence.",
            "",
            "Exploratory threshold intervals and hypothetical undercount scenarios are "
            "reported separately in paired_tests.json. They do not replace the fixed "
            "0.95 test or constitute observed agent claims.",
        ]
    return "\n".join(out) + "\n"


def main() -> None:
    text = render()
    (RESULTS / "RESULTS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
